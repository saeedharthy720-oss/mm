// Combines the two front-end builds into a single publish directory, so the
// storefront and the staff dashboard can be served from one domain:
//
//   dist/          <- apps/web/dist     (customer storefront, "/")
//   dist/admin/    <- apps/staff/dist   (staff dashboard, "/admin")
//
// They stay separate builds on purpose. Merging them into one bundle would make
// every customer download the dashboard code, which is both slower and more
// than they need to know about the admin surface.

import { access, cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "dist");

const sources = [
  { from: path.join(root, "apps", "web", "dist"), to: outDir, name: "storefront" },
  { from: path.join(root, "apps", "staff", "dist"), to: path.join(outDir, "admin"), name: "dashboard" }
];

for (const { from, name } of sources) {
  try {
    await access(from);
  } catch {
    console.error(`Missing build output for the ${name}: ${from}`);
    console.error("Run the app builds first (npm run build:web && npm run build:staff).");
    process.exit(1);
  }
}

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

for (const { from, to, name } of sources) {
  await cp(from, to, { recursive: true });
  console.log(`${name.padEnd(10)} ${path.relative(root, from)} -> ${path.relative(root, to) || "dist"}`);
}

// Routing and headers are written into the output rather than left in a
// host-specific config file. Netlify and Cloudflare Pages both read _redirects
// and _headers from the published directory, so the same build deploys to
// either one — which matters when a free tier runs out mid-project.
//
// Order is significant: the first matching rule wins, so /admin has to precede
// the catch-all. Only syntax both Netlify and Cloudflare Pages accept:
//   - status 200 means "rewrite", which both support
//   - no "!" force suffix; that is Netlify-only, and Cloudflare rejects the
//     whole file when it sees one rather than skipping the line. That is how
//     the first Cloudflare deploy ended up with no rules at all, leaving the
//     dashboard's deep links serving the storefront
//   - real files take precedence over rules on both, so assets still resolve
//
// There is deliberately no /api rule. Netlify allowed a 404 here as a guard
// against a build shipping without VITE_API_BASE_URL, but Cloudflare does not
// support that status, and an unsupported line costs the entire file. The
// guard that actually matters lives in apiClient.ts, which refuses to start
// rather than firing relative requests at the site itself.
const redirects = `# Generated by scripts/assemble-site.mjs — do not edit by hand.

# Staff dashboard (its own SPA, mounted at /admin).
#
# The destination is /admin.html, a copy of the dashboard's entry point that
# deliberately sits OUTSIDE the /admin/ directory. Rewriting to
# /admin/index.html instead looks more natural but is self-referential — the
# destination matches the "/admin/*" source pattern — and Cloudflare discards
# the rule, silently serving the storefront for every dashboard deep link.
# Netlify tolerates it because a rewrite there does not re-enter the rules.
#
# The bare /admin needs its own line: "/admin/*" does not match it.
/admin  /admin.html  200
/admin/*  /admin.html  200

# Customer storefront.
/*  /index.html  200
`;

const headers = `# Generated by scripts/assemble-site.mjs — do not edit by hand.

# Vite fingerprints asset filenames, so they can be cached forever.
/assets/*
  Cache-Control: public, max-age=31536000, immutable

/admin/assets/*
  Cache-Control: public, max-age=31536000, immutable

/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin

# The dashboard should never appear in search results.
/admin/*
  X-Robots-Tag: noindex, nofollow
`;

// The rewrite target described above. Also copied to admin/404.html: Cloudflare
// serves the nearest 404.html walking up from the requested path, so if the
// rewrite rule is ever dropped again the dashboard still loads instead of the
// storefront appearing in its place.
const dashboardEntry = await readFile(path.join(outDir, "admin", "index.html"), "utf8");
await writeFile(path.join(outDir, "admin.html"), dashboardEntry);
await writeFile(path.join(outDir, "admin", "404.html"), dashboardEntry);

await writeFile(path.join(outDir, "_redirects"), redirects);
await writeFile(path.join(outDir, "_headers"), headers);
console.log("config     _redirects, _headers, admin.html, admin/404.html -> dist");

console.log("Site assembled in dist/");
