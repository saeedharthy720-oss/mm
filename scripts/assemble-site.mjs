// Combines the two front-end builds into a single publish directory, so the
// storefront and the staff dashboard can be served from one domain:
//
//   dist/          <- apps/web/dist     (customer storefront, "/")
//   dist/admin/    <- apps/staff/dist   (staff dashboard, "/admin")
//
// They stay separate builds on purpose. Merging them into one bundle would make
// every customer download the dashboard code, which is both slower and more
// than they need to know about the admin surface.

import { access, cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "dist");

const sources = [
  { from: path.join(root, "apps", "web", "dist"), to: outDir, name: "storefront" },
  { from: path.join(root, "apps", "staff", "dist"), to: path.join(outDir, "admin"), name: "dashboard" }
];

for (const { from, name } of sources) {
  try {
    await access(from);
  } catch {
    console.error(`Missing build output for the ${name}: ${from}`);
    console.error("Run the app builds first (npm run build:web && npm run build:staff).");
    process.exit(1);
  }
}

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

for (const { from, to, name } of sources) {
  await cp(from, to, { recursive: true });
  console.log(`${name.padEnd(10)} ${path.relative(root, from)} -> ${path.relative(root, to) || "dist"}`);
}

// Routing and headers are written into the output rather than left in a
// host-specific config file. Netlify and Cloudflare Pages both read _redirects
// and _headers from the published directory, so the same build deploys to
// either one — which matters when a free tier runs out mid-project.
//
// Routing is done by a Worker rather than a _redirects file, because on
// Cloudflare Pages _redirects cannot express this site.
//
// Two separate single-page apps share one domain, so an unmatched path has to
// fall back to one of two different entry points depending on its prefix. Every
// way of saying that in _redirects failed, each differently:
//
//   /admin/* -> /admin/index.html   self-referential; the rule is discarded
//   /admin   -> /admin.html         collides with the /admin/ directory, 308 loop
//   /login   -> /index.html         Cloudflare canonicalises index.html away and
//                                   turns the rewrite into a 308 to "/", so the
//                                   login page redirected to the home page
//
// A Worker states the rule directly and returns a real 200. Note that supplying
// _worker.js means Pages stops processing _redirects and _headers, so the
// headers those used to set are applied here too.
const worker = `// Generated by scripts/assemble-site.mjs — do not edit by hand.

const IMMUTABLE_ASSETS = /^\\/(admin\\/)?assets\\//;

function withHeaders(response, pathname) {
  const headers = new Headers(response.headers);

  headers.set("X-Content-Type-Options", "nosniff");
  headers.set("X-Frame-Options", "DENY");
  headers.set("Referrer-Policy", "strict-origin-when-cross-origin");

  // The dashboard should never appear in search results.
  if (pathname === "/admin" || pathname.startsWith("/admin/")) {
    headers.set("X-Robots-Tag", "noindex, nofollow");
  }

  // Vite fingerprints asset filenames, so they can be cached indefinitely.
  if (IMMUTABLE_ASSETS.test(pathname)) {
    headers.set("Cache-Control", "public, max-age=31536000, immutable");
  }

  return new Response(response.body, { status: response.status, headers });
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    const asset = await env.ASSETS.fetch(request);
    if (asset.status !== 404) {
      return withHeaders(asset, url.pathname);
    }

    // Unmatched path: hand it to whichever app owns that prefix and let its
    // router decide. Requesting the directory rather than its index.html keeps
    // Cloudflare from canonicalising the URL and answering with a redirect.
    const isDashboard = url.pathname === "/admin" || url.pathname.startsWith("/admin/");
    const entry = new URL(isDashboard ? "/admin/" : "/", url.origin);
    const fallback = await env.ASSETS.fetch(new Request(entry, request));

    return withHeaders(new Response(fallback.body, { status: 200, headers: fallback.headers }), url.pathname);
  }
};
`;

// Kept as a safety net. If the Worker is ever removed or fails to deploy, Pages
// falls back to serving the nearest 404.html walking up from the requested
// path — which still lands each app on its own entry point rather than showing
// the storefront where the dashboard should be.
const dashboardEntry = await readFile(path.join(outDir, "admin", "index.html"), "utf8");
const storefrontEntry = await readFile(path.join(outDir, "index.html"), "utf8");
await writeFile(path.join(outDir, "admin", "404.html"), dashboardEntry);
await writeFile(path.join(outDir, "404.html"), storefrontEntry);

await writeFile(path.join(outDir, "_worker.js"), worker);
console.log("config     _worker.js, 404.html, admin/404.html -> dist");

console.log("Site assembled in dist/");
